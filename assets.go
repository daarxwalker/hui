package hui

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path"
	"path/filepath"
	"runtime/debug"
	"slices"
	"strings"
)

const (
	assetsModule    = "github.com/daarxwalker/hui"
	assetsDevel     = "(devel)"
	assetsHeadStart = "/* Generated by "
	assetsHeadEnd   = ". Do not edit. */"
)

//go:embed alpine/dist/module.esm.js
var moduleJS string

var ErrForeignAssets = errors.New("the directory holds files that no assets command generated")

func Assets() map[string][]byte {
	files := make(map[string][]byte)
	files["hui.js"] = []byte(AssetHeader(assetsModule) + moduleJS)
	return files
}

func AssetHeader(module string) string {
	return assetsHeadStart + module + " " + moduleVersion(module) + assetsHeadEnd + "\n"
}

func WriteAssets(dir string, files map[string][]byte) error {
	existing, err := readAssets(dir)
	if err != nil {
		return fmt.Errorf("read assets in %s failed: %w", dir, err)
	}
	if namesErr := checkAssetNames(files); namesErr != nil {
		return fmt.Errorf("check asset names failed: %w", namesErr)
	}
	if !generatedAssets(existing) {
		return fmt.Errorf("write assets to %s failed: %w", dir, ErrForeignAssets)
	}
	for _, name := range slices.Sorted(maps.Keys(files)) {
		content, ok := files[name]
		if !ok {
			continue
		}
		if current, found := existing[name]; found && bytes.Equal(current, content) {
			continue
		}
		target := filepath.Join(dir, filepath.FromSlash(name))
		if mkdirErr := os.MkdirAll(filepath.Dir(target), 0o755); mkdirErr != nil {
			return fmt.Errorf("create directory for %s failed: %w", name, mkdirErr)
		}
		if writeErr := os.WriteFile(target, content, 0o644); writeErr != nil {
			return fmt.Errorf("write %s failed: %w", name, writeErr)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(existing)) {
		if _, ok := files[name]; ok {
			continue
		}
		if removeErr := removeAsset(dir, name); removeErr != nil {
			return fmt.Errorf("remove stale %s failed: %w", name, removeErr)
		}
	}
	return nil
}

func CheckAssets(dir string, files map[string][]byte) ([]string, error) {
	existing, err := readAssets(dir)
	if err != nil {
		return nil, fmt.Errorf("read assets in %s failed: %w", dir, err)
	}
	if namesErr := checkAssetNames(files); namesErr != nil {
		return nil, fmt.Errorf("check asset names failed: %w", namesErr)
	}
	if !generatedAssets(existing) {
		return nil, fmt.Errorf("check assets in %s failed: %w", dir, ErrForeignAssets)
	}
	var changes []string
	for _, name := range slices.Sorted(maps.Keys(files)) {
		content, ok := files[name]
		if !ok {
			continue
		}
		current, found := existing[name]
		if !found {
			changes = append(changes, name+": missing")
			continue
		}
		if !bytes.Equal(current, content) {
			changes = append(changes, name+": differs, on disk "+assetOrigin(current))
		}
	}
	for _, name := range slices.Sorted(maps.Keys(existing)) {
		if _, ok := files[name]; ok {
			continue
		}
		current, found := existing[name]
		if !found {
			continue
		}
		changes = append(changes, name+": stale, on disk "+assetOrigin(current))
	}
	return changes, nil
}

func moduleVersion(module string) string {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return assetsDevel
	}
	if info.Main.Path == module {
		return buildVersion(info.Main)
	}
	for _, dep := range info.Deps {
		if dep.Path == module {
			return buildVersion(*dep)
		}
	}
	return assetsDevel
}

func buildVersion(module debug.Module) string {
	if module.Replace != nil {
		return buildVersion(*module.Replace)
	}
	if module.Version == "" {
		return assetsDevel
	}
	return module.Version
}

func readAssets(dir string) (map[string][]byte, error) {
	files := make(map[string][]byte)
	if _, statErr := os.Stat(dir); errors.Is(statErr, fs.ErrNotExist) {
		return files, nil
	}
	err := fs.WalkDir(os.DirFS(dir), ".", func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return fmt.Errorf("walk %s failed: %w", name, walkErr)
		}
		if !entry.Type().IsRegular() {
			return nil
		}
		content, readErr := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
		if readErr != nil {
			return fmt.Errorf("read %s failed: %w", name, readErr)
		}
		files[name] = content
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("walk %s failed: %w", dir, err)
	}
	return files, nil
}

func checkAssetNames(files map[string][]byte) error {
	for name := range files {
		if !fs.ValidPath(name) || name == "." {
			return fmt.Errorf("asset name %q is not a relative slash path", name)
		}
	}
	return nil
}

func generatedAssets(existing map[string][]byte) bool {
	if len(existing) == 0 {
		return true
	}
	for _, content := range existing {
		if _, ok := assetHeader(content); ok {
			return true
		}
	}
	return false
}

func assetOrigin(content []byte) string {
	header, ok := assetHeader(content)
	if !ok {
		return "not generated"
	}
	return "from " + header
}

func assetHeader(content []byte) (string, bool) {
	var zero string
	line, _, _ := bytes.Cut(content, []byte("\n"))
	header, found := strings.CutPrefix(string(line), assetsHeadStart)
	if !found {
		return zero, false
	}
	return strings.CutSuffix(header, assetsHeadEnd)
}

func removeAsset(dir, name string) error {
	if err := os.Remove(filepath.Join(dir, filepath.FromSlash(name))); err != nil {
		return fmt.Errorf("remove %s failed: %w", name, err)
	}
	for parent := path.Dir(name); parent != "."; parent = path.Dir(parent) {
		target := filepath.Join(dir, filepath.FromSlash(parent))
		entries, err := os.ReadDir(target)
		if err != nil {
			return fmt.Errorf("read directory %s failed: %w", parent, err)
		}
		if len(entries) > 0 {
			return nil
		}
		if removeErr := os.Remove(target); removeErr != nil {
			return fmt.Errorf("remove empty directory %s failed: %w", parent, removeErr)
		}
	}
	return nil
}
